var (
	// Version is set at build time
	Version = "dev"

	// Flags
	verbose       bool
	apiURL        string
	commandErrors commandErrorState
)

type commandErrorState struct {
	active     bool
	jsonOutput bool
	reported   bool
}

var rootCmd = &cobra.Command{
	Use:   "modernpath",
	Short: "ModernPath CLI - AI-powered codebase analysis and documentation",
	Long: `ModernPath CLI provides access to your codebase documentation
and analysis generated by the ModernPath platform.

Initialize a project with 'modernpath init', then use search and ask
to explore your documentation, and 'epics' commands to manage Epics and specifications.`,
	Version: Version,
	// Error paths return errors so exit codes are honest (REQ-CROSS-210);
	// without this every such error also dumps the full usage screen.
	SilenceUsage:  true,
	SilenceErrors: true,
	CompletionOptions: cobra.CompletionOptions{
		DisableDefaultCmd: true,
	},
}

// A command with a structured human error report still exits unsuccessfully,
// but Execute must not print its reason a second time.
type reportedError struct{ error }

func (e reportedError) Unwrap() error { return e.error }

// applyGroupUnknownArgGuard closes the D5 shape tree-wide: a group command
// (subcommands, no Run/RunE) that receives a token which is not one of its
// subcommands must error, not print help and exit 0 — that silent success is
// how `modernpath dev <tool>` masqueraded as working (REQ-CROSS-210;
// pre-PR review finding A1). Bare group invocations still show help.
// groupGuardAnnotation marks a group whose handler is this guard rather than
// a hand-written one. The guard mutates a shared tree, so without a marker a
// second application (or a test running after one) cannot tell a guarded
// group from a group that always had a handler.
const groupGuardAnnotation = "modernpath.group-unknown-arg-guard"

func applyGroupUnknownArgGuard(c *cobra.Command) {
	if len(c.Commands()) > 0 && c.Run == nil && c.RunE == nil {
		if c.Annotations == nil {
			c.Annotations = map[string]string{}
		}
		c.Annotations[groupGuardAnnotation] = "1"
		c.RunE = func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return cmd.Help()
			}
			return fmt.Errorf("unknown command %q for %q — run '%s --help'", args[0], cmd.CommandPath(), cmd.CommandPath())
		}
	}
	for _, sub := range c.Commands() {
		applyGroupUnknownArgGuard(sub)
	}
}

func Execute() {
	code := run(os.Args[1:])
	if code != 0 {
		exit(code)
	}
}

// run executes one invocation with args and returns its exit code; Execute
// is run(os.Args[1:]) plus the process exit.
func run(args []string) int {
	// The struct literal above captured Version at package init; a stamp set
	// later (main's embedded VERSION default) must still be what --version
	// prints.
	rootCmd.Version = Version
	applyGroupUnknownArgGuard(rootCmd)
	rootCmd.SetArgs(args)
	// REQ-CROSS-387: every user-run invocation is recorded (argv, exit, an
	// output tail) for `feedback --last`; the recorder drains before exit.
	return runWithHistory(args, func() int {
		beginCommandRun(args)
		_, err := rootCmd.ExecuteC()
		return finishCommandRun(err)
	})
}

func beginCommandRun(args []string) {
	commandErrors = commandErrorState{active: true, jsonOutput: requestsJSONOutput(args)}
}

func requestsJSONOutput(args []string) bool {
	for i, arg := range args {
		if arg == "--json" || arg == "--json=true" {
			return true
		}
		if arg == "--format=json" {
			return true
		}
		if arg == "--format" && i+1 < len(args) && args[i+1] == "json" {
			return true
		}
	}
	return false
}

func finishCommandRun(err error) (code int) {
	defer func() { commandErrors = commandErrorState{} }()
	if err == nil {
		if commandErrors.reported {
			return 1
		}
		return 0
	}
	if !commandErrors.reported {
		var reported reportedError
		if !errors.As(err, &reported) {
			writeCommandError(err.Error())
		}
	}
	var limiting serverLimitingError
	if errors.As(err, &limiting) {
		return 75
	}
	return 1
}

func writeCommandError(message string) {
	commandErrors.reported = true
	if commandErrors.jsonOutput {
		_ = json.NewEncoder(color.Error).Encode(map[string]string{"error": message})
		return
	}
	fmt.Fprintln(color.Error, message)
}

func init() {
	rootCmd.PersistentFlags().BoolVarP(&verbose, "verbose", "v", false, "verbose output")
	rootCmd.PersistentFlags().StringVar(&apiURL, "api-url", "", "ModernPath API URL (default: from config or api.modernpath.ai)")

	// Add subcommands
	rootCmd.AddCommand(initCmd)
	rootCmd.AddCommand(statusCmd)
	rootCmd.AddCommand(searchCmd)
	rootCmd.AddCommand(authCmd)
	// contextCmd lives in context.go — it backs the installed context hook
}

// Helper functions for output
func printSuccess(format string, a ...interface{}) {
	if commandErrors.jsonOutput {
		color.New(color.FgGreen).Fprintf(color.Error, ensureTrailingNewline("✓ "+format), a...)
		return
	}
	color.Green("✓ "+format, a...)
}

// Errors and warnings go to stderr so that --json and other pipeable output
// stays parseable on stdout (REQ-CROSS-210 D13, RUN:2026-08-18). The newline
// is conditional, mirroring fatih/color's own behavior — callers pass "\n"
// in their formats and must not get double-spaced (pre-PR review finding).
func printError(format string, a ...interface{}) {
	if !commandErrors.active {
		color.New(color.FgRed).Fprintf(color.Error, ensureTrailingNewline("✗ "+format), a...)
		return
	}
	if commandErrors.reported {
		return
	}
	message := fmt.Sprintf(format, a...)
	if commandErrors.jsonOutput {
		writeCommandError(strings.TrimSpace(message))
		return
	}
	commandErrors.reported = true
	color.New(color.FgRed).Fprintf(color.Error, ensureTrailingNewline("✗ "+format), a...)
}

func ensureTrailingNewline(format string) string {
	if strings.HasSuffix(format, "\n") {
		return format
	}
	return format + "\n"
}

func printInfo(format string, a ...interface{}) {
	color.New(color.FgCyan).Fprintf(color.Error, ensureTrailingNewline("→ "+format), a...)
}

func printWarning(format string, a ...interface{}) {
	color.New(color.FgYellow).Fprintf(color.Error, ensureTrailingNewline("⚠ "+format), a...)
}
