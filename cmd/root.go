// A command with a structured human error report still exits unsuccessfully,
// but Execute must not print its reason a second time.
type reportedError struct{ error }

func (e reportedError) Unwrap() error { return e.error }

// applyGroupUnknownArgGuard closes the D5 shape tree-wide: a group command
// (subcommands, no Run/RunE) that receives a token which is not one of its
// subcommands must error, not print help and exit 0 — that silent success is
// how `modernpath dev <tool>` masqueraded as working (REQ-CROSS-210;
// pre-PR review finding A1). Bare group invocations still show help.
// groupGuardAnnotation marks a group whose handler is this guard rather than
// a hand-written one. The guard mutates a shared tree, so without a marker a
// second application (or a test running after one) cannot tell a guarded
// group from a group that always had a handler.
const groupGuardAnnotation = "modernpath.group-unknown-arg-guard"

func applyGroupUnknownArgGuard(c *cobra.Command) {
	if len(c.Commands()) > 0 && c.Run == nil && c.RunE == nil {
		if c.Annotations == nil {
			c.Annotations = map[string]string{}
		}
		c.Annotations[groupGuardAnnotation] = "1"
		c.RunE = func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return cmd.Help()
			}
			return fmt.Errorf("unknown command %q for %q — run '%s --help'", args[0], cmd.CommandPath(), cmd.CommandPath())
		}
	}
	for _, sub := range c.Commands() {
		applyGroupUnknownArgGuard(sub)
	}
}

func Execute() {
	code := run(os.Args[1:])
	if code != 0 {
		exit(code)
	}
}

// run executes one invocation with args and returns its exit code; Execute
// is run(os.Args[1:]) plus the process exit.
func run(args []string) int {
	// The struct literal above captured Version at package init; a stamp set
	// later (main's embedded VERSION default) must still be what --version
	// prints.
	rootCmd.Version = Version
	applyGroupUnknownArgGuard(rootCmd)
	rootCmd.SetArgs(args)
	// Epic 422: decided before the command runs. A background lookup holds
	// the command up only after a cut-off, and then at its end (design 5a).
	update := beginUpdateCheck(args)
	var executed *cobra.Command
	var executeErr error
	// REQ-CROSS-387: every user-run invocation is recorded (argv, exit, an
	// output tail) in .modernpath/cli-history.log for local troubleshooting;
	// the recorder drains before exit.
	code := runWithHistory(args, func() int {
		beginCommandRun(args)
		executed, executeErr = rootCmd.ExecuteC()
		return finishCommandRun(executeErr)
	})
	update.finish(executed, executeErr)
	return code
}

// updateCheck is the update check's part of one run (Epic 422): the
// background lookup it may start before the command, and the --version
// status line or the update notice it may print after it.
type updateCheck struct {
	// eligible: a released build, the check on, no JSON, not a hook run, and
	// stdout and stderr both terminals.
	eligible bool
	folder   string // the CLI's folder under the user's cache folder, or ""
	cancel   context.CancelFunc
	done     <-chan struct{} // closes when the background lookup has ended
	// requestSent is set once the background lookup's request has gone out;
	// the lookup's goroutine sets it through the request's trace.
	requestSent atomic.Bool
	// waitUntil is set after a cut-off: the end of the run waits for the
	// background lookup until it ends or until then, 3 seconds after it
	// started on the real clock.
	waitUntil time.Time
}

// beginUpdateCheck decides whether this run may show the update notice or the
// --version status line, and starts the background lookup when the release
// cache has expired. prepare and --version look up themselves, offline runs
// stay off the network, and after a failed background lookup the next one
// waits an hour. After a cut-off the lookup gets 3 seconds and the end of the
// run waits for it.
func beginUpdateCheck(args []string) *updateCheck {
	u := &updateCheck{}
	if !releasedBuild(Version) || updateCheckOff() != "" || requestsJSONOutput(args) || hookMode(args) ||
		!streamIsTerminal(int(syscall.Stdout)) || !streamIsTerminal(int(syscall.Stderr)) {
		return u
	}
	u.eligible = true
	folder, ok := releaseFolder()
	if !ok {
		return u
	}
	u.folder = folder
	target, _, _ := rootCmd.Find(args)
	if target == prepareCmd || looksLikeVersionRun(args) || offlineRun(args, target) {
		return u
	}
	now := updateCheckClock()
	if _, _, fresh := readReleaseCache(folder, now); fresh || releaseLookupBackingOff(folder, now) || !releaseFolderWritable(folder) {
		return u
	}
	limit := releaseLookupLimit
	cutOff := releaseLookupCutOff(folder, now)
	if cutOff {
		limit = releaseLookupWaitLimit
	}
	ctx, cancel := context.WithTimeout(context.Background(), limit)
	if cutOff {
		u.waitUntil, _ = ctx.Deadline()
	}
	ctx = httptrace.WithClientTrace(ctx, &httptrace.ClientTrace{
		WroteRequest: func(info httptrace.WroteRequestInfo) {
			if info.Err == nil {
				u.requestSent.Store(true)
			}
		},
	})
	done := make(chan struct{})
	u.cancel, u.done = cancel, done
	go backgroundReleaseLookup(ctx, releaseLookupClient, releaseLookupURL, folder, updateCheckClock, done)
	if backgroundLookupStarted != nil {
		backgroundLookupStarted(done)
	}
	return u
}

// finish runs after runWithHistory has returned, with the real stdout and
// stderr back in place, so after the command's output, its exit code and its
// history entry. It ends the background lookup first: after a cut-off it waits
// for the lookup, and otherwise it cancels a lookup that is still running and
// records the cut-off when its request had gone out. Then it prints the
// --version status line or the update notice.
func (u *updateCheck) finish(executed *cobra.Command, err error) {
	u.endBackgroundLookup()
	if !u.eligible {
		return
	}
	if versionRun(executed, err) {
		status := checkRelease(context.Background(), Version, releaseLookupLimit)
		if line, warn := versionStatusLine(status, Version, runtime.GOOS); warn {
			printWarning("%s\n", line)
		} else if line != "" {
			fmt.Fprintln(color.Error, line)
		}
		return
	}
	if executed == prepareCmd || u.folder == "" {
		return
	}
	now := updateCheckClock()
	status := cachedReleaseStatus(u.folder, Version, now)
	if status.State != releaseNewer || !releaseNoticeDue(u.folder, status.Latest, now) {
		return
	}
	// A record that can't be written shows no line, so a read-only folder
	// never turns once a day into every command.
	if !writeReleaseFile(u.folder, releaseNoticeName, releaseNoticeFile{Tag: status.Latest, ShownAt: now.UTC().Format(time.RFC3339)}) {
		return
	}
	printWarning("%s\n", releaseNoticeLine(status.Latest, Version, runtime.GOOS))
}

// endBackgroundLookup ends the background lookup this run started, if any
// (design 5a).
func (u *updateCheck) endBackgroundLookup() {
	if u.cancel == nil {
		return
	}
	defer u.cancel()
	if !u.waitUntil.IsZero() {
		u.waitForLookup()
		return
	}
	select {
	case <-u.done:
	default:
		// The goroutine records nothing for a cancelled lookup, so this run
		// records the cut-off itself and waits for no goroutine. A request
		// written at the moment of the cancel can be recorded either way.
		u.cancel()
		if u.requestSent.Load() {
			recordReleaseCutOff(u.folder, updateCheckClock())
		}
	}
}

// waitForLookup waits, after a cut-off, until the background lookup ends or
// its 3 seconds run out on the real clock. A lookup that runs out is a failed
// lookup, recorded in place of the cut-off. A command that ran longer finds
// its lookup ended and doesn't wait.
func (u *updateCheck) waitForLookup() {
	select {
	case <-u.done:
		return
	default:
	}
	if backgroundLookupWaitStarted != nil {
		backgroundLookupWaitStarted()
	}
	timer := time.NewTimer(time.Until(u.waitUntil))
	defer timer.Stop()
	select {
	case <-u.done:
	case <-timer.C:
		recordReleaseFailure(u.folder, updateCheckClock())
	}
}

// backgroundReleaseLookup refreshes the release cache; it takes its client,
// URL, folder and clock when it starts. A lookup that run() cancels at the end
// of its command writes nothing; run() records the cut-off itself when the
// request had gone out. Any other failure, a timeout included, is recorded as
// failed_at alone in release-attempt.json, which ends a cut-off and holds the
// next background lookup back an hour.
func backgroundReleaseLookup(ctx context.Context, client *http.Client, url, folder string, clock func() time.Time, done chan<- struct{}) {
	defer close(done)
	tag, err := lookupLatestRelease(ctx, client, url)
	switch {
	case err == nil:
		writeReleaseCache(folder, tag, clock())
	case errors.Is(err, context.Canceled):
	default:
		recordReleaseFailure(folder, clock())
	}
}

// looksLikeVersionRun is run()'s guess, before cobra parses the flags, that
// args ask for --version: they resolve to the root command and --version (or
// --version=<value>) comes before any --. Such a run starts no background
// lookup, with or without -h or --help: --version looks up itself, and
// --help --version prints help and asks for no release (Epic 422). Whether it
// shows the status line is decided from what ExecuteC returns.
func looksLikeVersionRun(args []string) bool {
	if target, _, err := rootCmd.Find(args); err != nil || target != rootCmd {
		return false
	}
	for _, arg := range args {
		switch {
		case arg == "--":
			return false
		case arg == "--version" || strings.HasPrefix(arg, "--version="):
			return true
		}
	}
	return false
}

// versionRun says whether the command that ran printed --version: no error,
// the root command, its version flag on and its help flag off.
func versionRun(executed *cobra.Command, err error) bool {
	if err != nil || executed != rootCmd {
		return false
	}
	version, _ := rootCmd.Flags().GetBool("version")
	help, _ := rootCmd.Flags().GetBool("help")
	return version && !help
}

// offlineRun says whether a run promised not to reach the network: --offline
// (or --offline=true), or reverse-engineer check. It may still show the notice
// from a fresh cache, which is a local read.
func offlineRun(args []string, target *cobra.Command) bool {
	if target != nil && target.CommandPath() == "modernpath reverse-engineer check" {
		return true
	}
	for _, arg := range args {
		if arg == "--" {
			return false
		}
		if arg == "--offline" {
			return true
		}
		if value, ok := strings.CutPrefix(arg, "--offline="); ok {
			if on, err := strconv.ParseBool(value); err == nil && on {
				return true
			}
		}
	}
	return false
}

func beginCommandRun(args []string) {
	commandErrors = commandErrorState{active: true, jsonOutput: requestsJSONOutput(args)}
}

// requestsJSONOutput says whether args ask for JSON: --json, --json=<a value
// cobra reads as true, such as 1 or TRUE> (Epic 422, criterion 47c073a2), or
// --format json.
func requestsJSONOutput(args []string) bool {
	for i, arg := range args {
		if arg == "--json" {
			return true
		}
		if value, ok := strings.CutPrefix(arg, "--json="); ok {
			if on, err := strconv.ParseBool(value); err == nil && on {
				return true
			}
			continue
		}
		if arg == "--format=json" {
			return true
		}
		if arg == "--format" && i+1 < len(args) && args[i+1] == "json" {
			return true
		}
	}
	return false
}

func finishCommandRun(err error) (code int) {
	defer func() { commandErrors = commandErrorState{} }()
	if err == nil {
		if commandErrors.reported {
			return 1
		}
		return 0
	}
	if !commandErrors.reported {
		var reported reportedError
		if !errors.As(err, &reported) {
			writeCommandError(err.Error())
		}
	}
	var limiting serverLimitingError
	if errors.As(err, &limiting) {
		return 75
	}
	return 1
}

func writeCommandError(message string) {
	commandErrors.reported = true
	if commandErrors.jsonOutput {
		_ = json.NewEncoder(color.Error).Encode(map[string]string{"error": message})
		return
	}
	fmt.Fprintln(color.Error, message)
}

