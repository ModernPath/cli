// streamIsTerminal says whether a descriptor of the process is a terminal; a
// seam like stdinIsTerminal. The update check asks it about syscall.Stdout and
// syscall.Stderr, which the history capture never replaces.
var streamIsTerminal = func(fd int) bool { return term.IsTerminal(fd) }

