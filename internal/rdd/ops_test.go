func detailWithCriteria() string {
	return strings.Join([]string{
		"- **Status:** READY",
		"- **Acceptance criteria:**",
		"  - GIVEN a thing WHEN poked THEN it reacts.",
		"  - GIVEN only given THEN result.",
		"  - plain statement criterion",
		"- **Tests:** —",
	}, "\n")
}

func TestParseCriteriaSplitsGWTAndStatements(t *testing.T) {
	criteria := ParseCriteria(detailWithCriteria(), "REQ-TST-001")
	if len(criteria) != 3 {
		t.Fatalf("want 3 criteria, got %d", len(criteria))
	}
	first := criteria[0].(map[string]any)
	if first["given"] != "a thing" || first["when"] != "poked" || first["then"] != "it reacts." {
		t.Fatalf("GWT parse wrong: %v", first)
	}
	if first["external_id"] != "REQ-TST-001#AC1" || first["position"] != 1 {
		t.Fatalf("criterion identity wrong: %v", first)
	}
	second := criteria[1].(map[string]any)
	if second["given"] != "only given" || second["then"] != "result." {
		t.Fatalf("GIVEN/THEN (no WHEN) parse wrong: %v", second)
	}
	if _, hasWhen := second["when"]; hasWhen {
		t.Fatalf("no-WHEN criterion must omit the when key: %v", second)
	}
	third := criteria[2].(map[string]any)
	if third["statement"] != "plain statement criterion" {
		t.Fatalf("statement parse wrong: %v", third)
	}
}

// Hash-parity pins — generated by running the node op-builder on the same
// inputs (2026-07-28), and kept after it was retired. If these fail the
// canonicalization drifted from JSON.stringify semantics and a re-sync would
// churn every content hash.
func TestRequirementOpHashParityWithNodeBuilder(t *testing.T) {
	op := BuildRequirementOp(Req{
		ID:     "REQ-TST-001",
		Title:  `Title with · dots & "quotes"`,
		Ctx:    "TST",
		Stage:  "MVP",
		Status: "READY",
		Source: "`docs/10` · USER:2026-07-22 · EPIC-TST-001 · INV-TST-001",
		Detail: detailWithCriteria(),
	})
	if op.Type != "upsert_requirement" {
		t.Fatalf("wrong type %q", op.Type)
	}
	p := op.Payload
	if p["work_status"] != "READY" || p["context"] != "TST" || p["stage"] != "MVP" {
		t.Fatalf("field mapping wrong: %v", p)
	}
	cites := p["source_citations"].([]any)
	if len(cites) != 4 {
		t.Fatalf("want 4 citations, got %d", len(cites))
	}
	c0 := cites[0].(map[string]any)
	if c0["kind"] != "doc" || c0["ref"] != "docs/10" {
		t.Fatalf("citation classify wrong: %v", c0)
	}
	if c1 := cites[1].(map[string]any); c1["kind"] != "user" {
		t.Fatalf("USER: citation wrong: %v", c1)
	}
	// pins regenerated from the node builder after REQ-CROSS-222 added the
	// full-fidelity capture fields (detail_md/source_raw here)
	const nodeHash = "b5302eb659495c0562bf6683575f291ec8e8b8a93950d28c76542587c964ea0f"
	if p["content_hash"] != nodeHash {
		t.Fatalf("hash parity broken:\n  go:   %v\n  node: %s", p["content_hash"], nodeHash)
	}
}

