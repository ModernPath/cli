// REQ-CROSS-028 / SCN-SY-060+061: an epic's loop state is recorded in
// WORKLIST's own "Upper status" / "Lower status" columns (127 of 146 rows carry
// both) and was thrown away — only the Overall cell was read, to decide whether
// to open an approval gate. `initiatives.status` is NOT the target: it is the
// board column, which SERVER-SYNC-DESIGN §1.3 marks "untouched" and Core.Sync
// refuses to overwrite ("moving cards is the board's job").
func TestBuildEpicOpCarriesWorklistLoopStatuses(t *testing.T) {
	epic := Epic{
		ID:     "EPIC-X-001",
		Record: "epics/EPIC-X-001.md",
		Upper:  "UPPER_VALIDATED (live browser pass)",
		Lower:  "LOWER_VERIFIED",
	}
	p := BuildEpicOp(epic, "# EPIC-X-001 — t\n").Payload
	if p["upper_loop_status"] != "UPPER_VALIDATED (live browser pass)" {
		t.Fatalf("upper loop status not carried: %v", p["upper_loop_status"])
	}
	if p["lower_loop_status"] != "LOWER_VERIFIED" {
		t.Fatalf("lower loop status not carried: %v", p["lower_loop_status"])
	}
	if _, present := p["status"]; present {
		t.Fatal("must not send a board status — sync never moves cards (SERVER-SYNC-DESIGN §1.3)")
	}

	// An empty or em-dash cell is absence, not a status: the key stays off the
	// payload so those epics' content hashes do not move.
	bare := BuildEpicOp(Epic{ID: "EPIC-X-002", Record: "epics/EPIC-X-002.md", Upper: "—", Lower: ""}, "# EPIC-X-002 — t\n").Payload
	if _, present := bare["upper_loop_status"]; present {
		t.Fatal("em-dash must not sync as a status")
	}
	if _, present := bare["lower_loop_status"]; present {
		t.Fatal("empty cell must not sync as a status")
	}
}

