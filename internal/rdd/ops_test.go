// REQ-PLN-054 / D-MC-6 (USER:2026-08-07): a requirement's one-line description
// comes from its detail block's **Statement:** line; where the ledger has none
// (~69% of rows at decision time) it falls back to the first criterion's THEN
// clause — the outcome half reads as a summary where the full GWT does not.
// Neither present → empty (never invent one).
func TestParseDescriptionPrefersStatementThenFallsBackToThen(t *testing.T) {
	withStatement := "- **Status:** DONE\n- **Statement:** The face shows every model we can call.\n" +
		"- **Acceptance criteria:**\n  - GIVEN a user WHEN it loads THEN the catalog renders.\n"
	if got := ParseDescription(withStatement); got != "The face shows every model we can call." {
		t.Fatalf("statement not used: %q", got)
	}

	criteriaOnly := "- **Status:** DONE\n- **Acceptance criteria:**\n" +
		"  - GIVEN a batch WHEN applied THEN the release row exists and every row carries its id.\n"
	if got := ParseDescription(criteriaOnly); got != "The release row exists and every row carries its id." {
		t.Fatalf("THEN fallback wrong: %q", got)
	}

	if got := ParseDescription("- **Status:** DONE\n- **Tests:** —\n"); got != "" {
		t.Fatalf("expected empty, got %q", got)
	}
	if got := ParseDescription(""); got != "" {
		t.Fatalf("expected empty for no detail, got %q", got)
	}
}

