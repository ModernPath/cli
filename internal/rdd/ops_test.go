// The single-UR reader takes the FIRST id-led heading and nothing else: a
// leading heading whose body states nothing yields nothing, rather than
// reaching past it to a later heading. Walking every heading is the plural
// reader's job, and the two must not be collapsed into one — the mirror in
// ops.js has to make the same distinction or the builders drift.
func TestSingleReaderStopsAtTheFirstIDLedHeading(t *testing.T) {
	record := `# EPIC-LED-001 — two id-led headings

## UR-LED-001 — the first outcome

## UR-LED-002 — the second outcome

As an operator I want the second outcome so that it is delivered.
`
	if ur, ok := ParseEpicUserRequirement(record); ok {
		t.Fatalf("the statement-less leading heading was skipped: %+v", ur)
	}
	got := urIDsOf(ParseEpicUserRequirements(record))
	if len(got) != 1 || got[0] != "UR-LED-002" {
		t.Fatalf("declared user requirements = %v, want only the heading that states one", got)
	}
}

// Three consecutive id-led headings, each stating its outcome. A reader that
// scans one pattern over the whole record consumes the `\n##` that ends each
// body, so its next scan starts inside the following heading line and misses
// it: three headings read as the first and the third. Walking the headings by
// index is what keeps the middle one, and only a record with three of them can
// tell the two readings apart — with two, the swallowed one is the last, and a
// reader that loses the last looks the same as one that stops early.
const threeIDLedOutcomesRecord = `# EPIC-LED-001 — three id-led headings

## UR-LED-001 — the first outcome

As a reader I want the first outcome so that it is delivered.

## UR-LED-002 — the second outcome

As an operator I want the second outcome so that it is delivered.

## UR-LED-003 — the third outcome

As an auditor I want the third outcome so that it is delivered.
`

func TestEveryIDLedHeadingIsReadNotEverySecondOne(t *testing.T) {
	got := urIDsOf(parseIDLedOutcomes(threeIDLedOutcomesRecord))
	want := []string{"UR-LED-001", "UR-LED-002", "UR-LED-003"}
	if len(got) != len(want) {
		t.Fatalf("id-led outcomes = %v, want %v", got, want)
	}
	for i, id := range want {
		if got[i] != id {
			t.Fatalf("id-led outcomes = %v, want %v", got, want)
		}
	}
	// Each statement comes from its own heading's body, not a neighbour's.
	for _, ur := range parseIDLedOutcomes(threeIDLedOutcomesRecord) {
		switch ur.ID {
		case "UR-LED-001":
			if !strings.Contains(ur.Statement, "first outcome") {
				t.Errorf("%s took a neighbour's body: %q", ur.ID, ur.Statement)
			}
		case "UR-LED-002":
			if !strings.Contains(ur.Statement, "second outcome") {
				t.Errorf("%s took a neighbour's body: %q", ur.ID, ur.Statement)
			}
		case "UR-LED-003":
			if !strings.Contains(ur.Statement, "third outcome") {
				t.Errorf("%s took a neighbour's body: %q", ur.ID, ur.Statement)
			}
		}
	}
	if ids := urIDsOf(ParseEpicUserRequirements(threeIDLedOutcomesRecord)); len(ids) != 3 {
		t.Fatalf("declared user requirements = %v, want all three", ids)
	}
	// The singular reader still answers its own question: the leading one.
	if ur, ok := ParseEpicUserRequirement(threeIDLedOutcomesRecord); !ok || ur.ID != "UR-LED-001" {
		t.Fatalf("single-UR reader = %q/%v, want UR-LED-001", ur.ID, ok)
	}
}

// A row that names a user requirement and states nothing about it is not a
// declaration the builder can carry: an entity built from it would need its
// statement invented, and an invented user requirement is indistinguishable
// from a real one. Both the shape readers and the collector enforce this, so
// the pin has to name the outcome rather than either guard.
func TestADeclarationNeedsBothAnIDAndAStatement(t *testing.T) {
	record := `# EPIC-BLANK-001 - a stated row and a blank one

## Linked user requirements

| User requirement | Statement | Status |
|---|---|---|
| UR-BLANK-001 | The system shall do the thing that is stated. | VALIDATED |
| UR-BLANK-002 |  | IN_PROGRESS |
`
	got := urIDsOf(ParseEpicUserRequirements(record))
	if len(got) != 1 || got[0] != "UR-BLANK-001" {
		t.Fatalf("declared user requirements = %v, want only the stated row", got)
	}

	// …and nothing downstream invents one either: no membership edge and no
	// entity for the blank row.
	op := BuildEpicOp(Epic{ID: "EPIC-BLANK-001", State: "in-progress"}, record)
	ids, _ := op.Payload["user_requirement_external_ids"].([]string)
	if len(ids) != 1 || ids[0] != "UR-BLANK-001" {
		t.Fatalf("user_requirement_external_ids = %v, want only the stated row", op.Payload["user_requirement_external_ids"])
	}
	ops := BuildOps(Data{Epics: []Epic{{ID: "EPIC-BLANK-001", Record: "epics/EPIC-BLANK-001.md", State: "in-progress"}}},
		func(string) string { return record }, "2026-08-22")
	for _, o := range ops {
		if o.Type == "upsert_requirement" && o.Payload["kind"] == "user" && o.Payload["external_id"] == "UR-BLANK-002" {
			t.Fatalf("the blank row reached a user-requirement op: %v", o.Payload)
		}
	}
}

// REQ-PLN-054: "the user outcome is what an epic IS about; without it the app
// can only show an id and a title." ParseEpicDescription read exactly one
// shape — a `## User outcome` heading — so 34 of 190 epic records landed with
// no description at all, while 186 of the 190 fit the heading rule.
//
// The fallbacks are ordered by how much they assume, and both are grounded in
// what the corpus was measured to contain:
//
//  1. The user-requirement statement the EXISTING parsers already extract.
//     Nine of the 34 declare their outcome as a labelled bullet —
//     `- **User outcome (UR-SYNC-001):** …`, `- **UR:** …` — which
//     ParseEpicUserRequirement reads today. Reusing it invents nothing: it is
//     the same sentence, from a parser that already recognizes the shape.
//
//  2. Failing that, the record's opening paragraph — but only when it is
//     prose. Twenty-six records open with a real description ("A real UX fix:
//     the Knowledge Core Capabilities table renders every capability…"), and
//     the rest open with a metadata banner (`- **Status:** IN_PROGRESS ·
//     **Owner:** …`). A list is never a description, so a leading list marker
//     disqualifies the paragraph rather than filling the field with metadata.
//
// The heading path is untouched, so no epic that has a description today gets
// a different one — and no content hash moves for them.
func TestEpicDescriptionFallsBackToWhatTheRecordDeclares(t *testing.T) {
	// 1. The heading still wins, unchanged.
	heading := "# EPIC-CV-001 — Only\n\n## User outcome\nThe portfolio renders real systems.\n"
	if got := ParseEpicDescription(heading); got != "The portfolio renders real systems." {
		t.Errorf("heading path changed: %q", got)
	}

	// 2. A labelled outcome bullet, the shape nine records use.
	bullet := "# EPIC-SYNC-001 — Sync\n\n" +
		"- **Status:** IN_REVIEW (evidence-complete)\n" +
		"- **User outcome (UR-SYNC-001):** As the team, we see our requirements inside ModernPath itself.\n\n" +
		"## Scenarios\n"
	got := ParseEpicDescription(bullet)
	if !strings.Contains(got, "we see our requirements inside ModernPath") {
		t.Errorf("description = %q, want the outcome the bullet declares", got)
	}
	if strings.Contains(got, "IN_REVIEW") {
		t.Errorf("description = %q, must not be the status banner", got)
	}

	// 3. An opening prose paragraph is a description.
	prose := "# EPIC-FE-022 — Capabilities filter\n\n" +
		"A real UX fix: the Knowledge Core Capabilities table renders every capability a system\n" +
		"has with no way to narrow it.\n\n## Tasks\n"
	got = ParseEpicDescription(prose)
	if !strings.Contains(got, "A real UX fix") {
		t.Errorf("description = %q, want the opening paragraph", got)
	}
	// Hard-wrapped prose is one sentence, not one line.
	if !strings.Contains(got, "no way to narrow it") {
		t.Errorf("description = %q, want the whole wrapped paragraph", got)
	}

	// 4. A bolded lead is prose, not a list.
	bold := "# EPIC-FE-037 — Downgrade fix\n\n" +
		"**A defect found in an honest self-review of the branch.** The inline editor\n" +
		"could not downgrade a full-access key.\n\n## Tasks\n"
	if got = ParseEpicDescription(bold); !strings.Contains(got, "honest self-review") {
		t.Errorf("description = %q, want the bolded prose lead", got)
	}

	// 5. A metadata banner is not a description — better empty than wrong.
	meta := "# EPIC-AUTH-001 — Login\n\n" +
		"- **Status:** IN_PROGRESS · **Owner:** Pasi (approval) · **Started:** 2026-08-06\n" +
		"- **Ledger:** `REQ-PLT-016`\n\n## Tasks\n"
	if got = ParseEpicDescription(meta); got != "" {
		t.Errorf("description = %q, want empty — a status banner is not an outcome", got)
	}
}
