// Generate creates the modernpath_agents.md file
func Generate(ctx *TransformContext, outputPath string) error {
	funcMap := template.FuncMap{
		"title": strings.Title,
	}

	tmpl, err := template.New("agents_md").Funcs(funcMap).Parse(agentsMDTemplate)
	if err != nil {
		return fmt.Errorf("failed to parse template: %w", err)
	}

	if ctx.GeneratedAt == "" {
		ctx.GeneratedAt = time.Now().Format("2006-01-02 15:04:05")
	}
	if ctx.CLIVersion == "" {
		ctx.CLIVersion = "dev"
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, ctx); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	// Ensure output directory exists
	if dir := filepath.Dir(outputPath); dir != "." {
		if err := os.MkdirAll(dir, 0755); err != nil {
			return fmt.Errorf("failed to create output directory: %w", err)
		}
	}

	if err := os.WriteFile(outputPath, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}

	return nil
}

// GenerateFromManifest generates modernpath_agents.md from the manifest file
func GenerateFromManifest(manifestPath, outputPath string) error {
	// Read manifest
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return fmt.Errorf("failed to read manifest: %w", err)
	}

	var manifest struct {
		InitiativeID         int    `json:"initiative_id"`
		InitiativeName       string `json:"initiative_name"`
		SourceSystemID int    `json:"source_system_id"`
		TargetSystemID int    `json:"target_system_id"`
		TotalFiles           int    `json:"total_files"`
		SyncedFiles          int    `json:"synced_files"`
		SyncedAt             string `json:"synced_at"`
		Files                []struct {
			Name       string `json:"name"`
			FilePath   string `json:"file_path"`
			Language   string `json:"language"`
			TotalLines int    `json:"total_lines"`
			Purpose    string `json:"purpose"`
			Summary    string `json:"summary"`
		} `json:"files"`
	}

	if err := json.Unmarshal(data, &manifest); err != nil {
		return fmt.Errorf("failed to parse manifest: %w", err)
	}

	// Build context
	ctx := &TransformContext{
		InitiativeID:   manifest.InitiativeID,
		InitiativeName: manifest.InitiativeName,
		SourceSystemID:   manifest.SourceSystemID,
		TargetSystemID:   manifest.TargetSystemID,
		SourceSystemName: fmt.Sprintf("System %d", manifest.SourceSystemID),
		TargetSystemName: fmt.Sprintf("System %d", manifest.TargetSystemID),
		SourceFiles:    make([]SourceFile, 0, len(manifest.Files)),
	}

	for _, f := range manifest.Files {
		ctx.SourceFiles = append(ctx.SourceFiles, SourceFile{
			Name:       f.Name,
			FilePath:   f.FilePath,
			Language:   f.Language,
			TotalLines: f.TotalLines,
			Purpose:    f.Purpose,
			Summary:    f.Summary,
		})
	}

	// Scan for specs
	specsDir := filepath.Join(filepath.Dir(manifestPath), "..", "specs")
	if entries, err := os.ReadDir(specsDir); err == nil {
		for _, entry := range entries {
			if entry.IsDir() {
				ctx.SpecCategories = append(ctx.SpecCategories, entry.Name())
			}
		}
	}

	// Scan for docs
	docsDir := filepath.Join(filepath.Dir(manifestPath), "..", "docs")
	if entries, err := os.ReadDir(docsDir); err == nil {
		for _, entry := range entries {
			if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".md") {
				name := strings.TrimSuffix(entry.Name(), ".md")
				ctx.Docs = append(ctx.Docs, Document{
					Title: name,
					Tier:  "synced",
					Angle: "local",
				})
			}
		}
	}

	return Generate(ctx, outputPath)
}
