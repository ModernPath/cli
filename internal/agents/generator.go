// TransformContext holds all the context needed to generate modernpath_agents.md
type TransformContext struct {
	InitiativeID   int
	InitiativeName string
	SourceSystemID   int
	TargetSystemID   int
	SourceSystemName string
	TargetSystemName string
	ProjectType    string

	// Transform items (source files)
	SourceFiles []SourceFile

	// Source system documentation
	SourceDocs []SourceDoc

	// Target system documentation
	Docs []Document

	// Specifications
	Specs          []SpecFile
	SpecCategories []string

	// Metadata
	GeneratedAt string
	CLIVersion  string
}

// SourceFile represents a file to be transformed
type SourceFile struct {
	Name       string
	FilePath   string
	Language   string
	TotalLines int
	Purpose    string
	Summary    string
	Approach   string // rewrite, refactor, wrap
	Priority   string // high, medium, low
}

// Document represents a system document
type Document struct {
	ID      string
	Title   string
	Tier    string
	Angle   string
	Summary string
}

// SourceDoc represents a source system document synced locally
type SourceDoc struct {
	ID       string
	Title    string
	Tier     string
	Angle    string
	Summary  string
	FilePath string // Relative path in .modernpath/source_docs/
}

// SpecFile represents a specification file
type SpecFile struct {
	Name     string
	Category string
	Path     string
}

